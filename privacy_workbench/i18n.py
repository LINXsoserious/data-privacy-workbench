REASON_KEYS = (
    "reason_future_date", "reason_invalid_date", "reason_checksum",
    "reason_id_passed", "reason_phone", "reason_email",
)


def normalize_lang(lang: str = "zh") -> str:
    """Unknown locales deterministically fall back to the existing Chinese UI."""
    return "en" if lang in {"en", "English"} else "zh"


def translate(key: str, lang: str = "zh", **values) -> str:
    return MESSAGES[normalize_lang(lang)][key].format(**values)


def labels(lang: str = "zh") -> dict[str, str]:
    return {kind: translate(kind, lang) for kind in ("phone", "email", "id_card")}


def localize_reason(reason: str, lang: str = "zh") -> str:
    """Only known application-generated notes are translated, never arbitrary evidence."""
    for key in REASON_KEYS:
        if any(reason == messages[key] for messages in MESSAGES.values()):
            return translate(key, lang)
    return reason
